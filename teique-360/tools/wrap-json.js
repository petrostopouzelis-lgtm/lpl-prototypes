// Writes script versions of the JSON files, so the pages open by double-click (no server, no fetch).
//   text/library.json    -> text/library.js      (window.TEIQ_TEXT)
//   data/sample-360.json -> data/sample-360.js   (window.TEIQ_SAMPLE)
//   every data/*.json    -> data/<name>.js       (window.TEIQ_FILES[<name>]), used by the page viewer
const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
const head = json => '// Generated by tools/wrap-json.js from ' + json + '. Do not edit.\n';
const read = json => fs.readFileSync(path.join(root, json), 'utf8').trim();

fs.writeFileSync(path.join(root, 'text/library.js'), head('text/library.json') + 'window.TEIQ_TEXT = ' + read('text/library.json') + ';\n');
const names = fs.readdirSync(path.join(root, 'data')).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).sort((a, b) => (a === 'sample-360' ? -1 : b === 'sample-360' ? 1 : a.localeCompare(b)));
names.forEach(n => {
  const json = `data/${n}.json`, body = read(json);
  fs.writeFileSync(path.join(root, `data/${n}.js`), head(json) + `(window.TEIQ_FILES = window.TEIQ_FILES || {})[${JSON.stringify(n)}] = ${body};\n` + (n === 'sample-360' ? 'window.TEIQ_SAMPLE = window.TEIQ_FILES["sample-360"];\n' : ''));
});
fs.writeFileSync(path.join(root, 'data/files.js'), '// Generated by tools/wrap-json.js. The data files the page viewer can show.\nwindow.TEIQ_FILE_LIST = ' + JSON.stringify(names) + ';\n');
console.log('wrote text/library.js and', names.length, 'data scripts');
