// Copies the TEIQue 360° report into the coach account prototype (user platforms/coach account/),
// so that account stays self-contained (it opens by double-click and publishes as one folder):
//   teique360/            the report and chart code, the wording, and the coach's 360° data
//   assets/reports/       the finished PDF of that 360°, for the Download buttons
//   assets/report-covers/teique-360.png   the cover, as a thumbnail for the assignment wizard
// The coach's 360° is the sample report under the name of one of the account's candidates.
// Run it again after changing the report code, the wording or the sample.
//   node tools/sync-coach-account.js        (set CHROME_PATH if Chrome or Edge is not found)
const fs = require('fs'), path = require('path'), os = require('os'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '..');
const acct = path.join(root, '..', 'user platforms', 'coach account');
if (!fs.existsSync(acct)) throw new Error('No coach account at ' + acct + ' (run "user platforms/restore-account.py" first).');

const CANDIDATE = { name: 'James Okoro', file: 'james-okoro', date: '2026-06-12', id: 'SAMPLE-0001' };

// 1. code and wording
const out = path.join(acct, 'teique360');
fs.mkdirSync(path.join(out, 'charts'), { recursive: true });
['src/model.js', 'src/svg.js', 'src/charts/radial.js', 'src/charts/linear.js', 'src/charts/overview.js', 'src/report/content.js', 'text/library.js']
  .forEach(f => fs.copyFileSync(path.join(root, f), path.join(out, f.startsWith('src/charts/') ? 'charts/' + path.basename(f) : path.basename(f))));

// 2. the candidate's 360° data: the sample, under the candidate's name and date
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/sample-360.json'), 'utf8'));
data.subject.name = CANDIDATE.name;
data.report.date = CANDIDATE.date;
data.report.id = CANDIDATE.id;
const json = path.join(out, `data-${CANDIDATE.file}.json`);
fs.writeFileSync(json, JSON.stringify(data, null, 2) + '\n');
fs.writeFileSync(path.join(out, `data-${CANDIDATE.file}.js`),
  `// Generated by teique-360/tools/sync-coach-account.js. Do not edit.\nwindow.TEIQ_COACH_360 = ${JSON.stringify(data, null, 2)};\n`);

// 3. the finished PDF (no review tags), and its cover as a thumbnail
const reports = path.join(acct, 'assets', 'reports');
fs.mkdirSync(reports, { recursive: true });
const pdf = path.join(reports, `teique360-${CANDIDATE.file}.pdf`);
const pngDir = fs.mkdtempSync(path.join(os.tmpdir(), 'coach360-'));
process.stdout.write(execFileSync(process.execPath, [path.join(__dirname, 'build-pdf.js'), json, pdf, '--no-marks', '--png=' + pngDir], { encoding: 'utf8' }));
fs.copyFileSync(path.join(pngDir, 'page-01.png'), path.join(acct, 'assets', 'report-covers', 'teique-360.png'));
fs.rmSync(pngDir, { recursive: true, force: true });
console.log('coach account updated:', path.relative(path.join(root, '..'), out), '+ PDF + cover thumbnail');
