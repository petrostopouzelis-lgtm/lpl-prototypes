// Writes src/hub/embed.js: the fonts, report images and report stylesheet as one script, for the hub's
// exports. A chart drawn into a PNG cannot see the page's fonts, and an exported report has to carry
// its own fonts, images and styles; a page opened by double-click cannot fetch files, but it can load
// a script. Run it again after changing src/report/report.css, ../teique-ff/src/ff.css, the fonts or the report images.
//   node tools/build-hub-embed.js
const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
const b64 = f => fs.readFileSync(path.join(root, f)).toString('base64');
const images = {};
[['assets/cover-2026.jpg', 'image/jpeg'], ['assets/back-cover.jpg', 'image/jpeg'], ['assets/logo-monogram.png', 'image/png']]
  .forEach(([f, type]) => { images[f] = `data:${type};base64,${b64(f)}`; });
const embed = {
  fonts: { Inter: b64('fonts/Inter-Variable.ttf'), Manrope: b64('fonts/Manrope-Variable.ttf') },
  images,
  reportCss: fs.readFileSync(path.join(root, 'src/report/report.css'), 'utf8'),
  // the Full Form report's own styles, added to an exported Full Form report
  ffCss: fs.readFileSync(path.join(root, '../teique-ff/src/ff.css'), 'utf8')
};
fs.mkdirSync(path.join(root, 'src/hub'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/hub/embed.js'), '// Generated by tools/build-hub-embed.js. Do not edit.\nwindow.TEIQ_EMBED = ' + JSON.stringify(embed) + ';\n');
console.log('wrote src/hub/embed.js', Math.round(fs.statSync(path.join(root, 'src/hub/embed.js')).size / 1024), 'KB');
