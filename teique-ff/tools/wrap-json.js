// Writes script versions of the data files, so report.html opens by double-click (no server, no fetch).
//   every data/*.json -> data/<name>.js (window.TEIQ_FF_FILES[<name>]); the list goes in data/files.js
// text/library.js is written by tools/build-library.py.
const fs = require('fs'), path = require('path'), root = path.join(__dirname, '..');
const names = fs.readdirSync(path.join(root, 'data')).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5))
  .sort((a, b) => (a === 'sample-ff' ? -1 : b === 'sample-ff' ? 1 : a.localeCompare(b)));
names.forEach(n => {
  const json = `data/${n}.json`, body = fs.readFileSync(path.join(root, json), 'utf8').trim();
  JSON.parse(body);
  fs.writeFileSync(path.join(root, `data/${n}.js`), `// Generated by tools/wrap-json.js from ${json}. Do not edit.\n(window.TEIQ_FF_FILES = window.TEIQ_FF_FILES || {})[${JSON.stringify(n)}] = ${body};\n`);
});
fs.writeFileSync(path.join(root, 'data/files.js'), '// Generated by tools/wrap-json.js. The data files the page viewer can show.\nwindow.TEIQ_FF_FILE_LIST = ' + JSON.stringify(names) + ';\n');
console.log('wrote', names.length, 'data scripts');
